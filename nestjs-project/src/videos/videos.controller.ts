import { Controller, Get, Param, Redirect } from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiOperation,
  ApiResponse,
  ApiTags,
  getSchemaPath,
} from '@nestjs/swagger';
import type { JwtPayload } from '../auth/auth.types';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import { ApiErrorEnvelope } from '../common/openapi/api-error-envelope.dto';
import { VideoResponseDto } from './dto/video-response.dto';
import { VideoDeliveryService } from './video-delivery.service';
import { VideosService } from './videos.service';

@ApiTags('videos')
@Controller('videos')
export class VideosController {
  constructor(
    private readonly videosService: VideosService,
    private readonly videoDeliveryService: VideoDeliveryService,
  ) {}

  @Get(':publicId')
  @ApiBearerAuth('access-token')
  @ApiOperation({
    summary: 'Get a video',
    description:
      'Returns the video data and its processing status so the owner can follow the upload until it is ready or failed.',
  })
  @ApiResponse({
    status: 200,
    description: 'The video',
    type: VideoResponseDto,
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or invalid access token',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 404,
    description: 'Video not found or owned by another user',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  async findOne(
    @CurrentUser() user: JwtPayload,
    @Param('publicId') publicId: string,
  ): Promise<VideoResponseDto> {
    return VideoResponseDto.from(
      await this.videosService.findOwnedByPublicId(publicId, user.sub),
    );
  }

  @Get(':publicId/stream')
  @Redirect()
  @ApiBearerAuth('access-token')
  @ApiOperation({
    summary: 'Stream a video',
    description:
      'Authorizes the owner and redirects to a presigned storage URL that serves HTTP Range requests (206) for playback.',
  })
  @ApiResponse({
    status: 302,
    description: 'Redirect to the presigned storage URL (Location header)',
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or invalid access token',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 404,
    description: 'Video not found or owned by another user',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 409,
    description: 'Video is not ready yet',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  async stream(
    @CurrentUser() user: JwtPayload,
    @Param('publicId') publicId: string,
  ): Promise<{ url: string; statusCode: number }> {
    return {
      url: await this.videoDeliveryService.getStreamUrl(user.sub, publicId),
      statusCode: 302,
    };
  }

  @Get(':publicId/download')
  @Redirect()
  @ApiBearerAuth('access-token')
  @ApiOperation({
    summary: 'Download a video',
    description:
      'Authorizes the owner and redirects to a presigned storage URL that forces Content-Disposition: attachment with the original file name.',
  })
  @ApiResponse({
    status: 302,
    description: 'Redirect to the presigned storage URL (Location header)',
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or invalid access token',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 404,
    description: 'Video not found or owned by another user',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 409,
    description: 'Video is not ready yet',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  async download(
    @CurrentUser() user: JwtPayload,
    @Param('publicId') publicId: string,
  ): Promise<{ url: string; statusCode: number }> {
    return {
      url: await this.videoDeliveryService.getDownloadUrl(user.sub, publicId),
      statusCode: 302,
    };
  }

  @Get(':publicId/thumbnail')
  @Redirect()
  @ApiBearerAuth('access-token')
  @ApiOperation({
    summary: 'Get a video thumbnail',
    description:
      'Authorizes the owner and redirects to a presigned storage URL of the thumbnail generated by the worker.',
  })
  @ApiResponse({
    status: 302,
    description: 'Redirect to the presigned storage URL (Location header)',
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or invalid access token',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 404,
    description: 'Video not found or owned by another user',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  @ApiResponse({
    status: 409,
    description: 'Video has no thumbnail yet (not processed)',
    schema: { $ref: getSchemaPath(ApiErrorEnvelope) },
  })
  async thumbnail(
    @CurrentUser() user: JwtPayload,
    @Param('publicId') publicId: string,
  ): Promise<{ url: string; statusCode: number }> {
    return {
      url: await this.videoDeliveryService.getThumbnailUrl(user.sub, publicId),
      statusCode: 302,
    };
  }
}
